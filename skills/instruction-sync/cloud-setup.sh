#!/bin/bash
# Write $AGENT_INSTRUCTIONS_STATE/cloud-setup.sh: a setup script for a personal Claude Code cloud
# environment. Cloud sessions don't read this machine's ~/.claude, so the script recreates the
# instruction files in the cloud VM and a ~/.claude/CLAUDE.md that imports them.
#   Includes ENGINEERING.md; the personal overlay only when $AGENT_INSTRUCTIONS_STATE/.cloud-include-personal
#   exists (its text then lives in the environment config).
#   exit 0  written or already current
#   exit 1  stopped: a source contains the heredoc delimiter
set -u
R="${AGENT_INSTRUCTIONS_DIR:-$HOME/agent-instructions}"
P="${AGENT_INSTRUCTIONS_OVERLAY:-$HOME/agent-instructions-personal.md}"
S="${AGENT_INSTRUCTIONS_STATE:-$HOME/.agent-instructions}"
OUT="$S/cloud-setup.sh"
FLAG="$S/.cloud-include-personal"
DELIM="AGENT_INSTRUCTIONS_END_7f3c"
mkdir -p "$S"

# Source file → path in the cloud VM (relative to $HOME).
srcs=("$R/ENGINEERING.md")
dsts=("agent-instructions/ENGINEERING.md")
if [ -e "$FLAG" ] && [ -f "$P" ]; then
  srcs+=("$P")
  dsts+=("agent-instructions-personal.md")
fi

for f in "${srcs[@]}"; do
  if grep -qxF "$DELIM" "$f"; then
    echo "STOP: $f contains a line '$DELIM'; pick another delimiter in $0."
    exit 1
  fi
done

T=$(mktemp); trap 'rm -f "$T"' EXIT
{
  echo '#!/bin/bash'
  echo '# Generated by instruction-sync. Do not edit; paste the whole file into your cloud'
  echo '# environment'"'"'s setup script.'
  echo 'set -e'
  echo 'mkdir -p "$HOME/agent-instructions" "$HOME/.claude"'
  for i in "${!srcs[@]}"; do
    echo
    echo "cat > \"\$HOME/${dsts[$i]}\" <<'$DELIM'"
    cat "${srcs[$i]}"
    # Keep the delimiter on its own line even when the source has no trailing newline.
    [ -n "$(tail -c 1 "${srcs[$i]}")" ] && echo
    echo "$DELIM"
  done
  echo
  echo "cat > \"\$HOME/.claude/CLAUDE.md\" <<'$DELIM'"
  for d in "${dsts[@]}"; do echo "@~/$d"; done
  cat <<'EOF'

# Cloud session

This is a Claude Code cloud session. The session-title hook from the instructions above doesn't
run here, and you can't rename this session yourself. Whenever the title rules call for a new
title (scope or PR changed; my message is just "Done", "Close", "Pin" or "Unpin"; or I continue a
✅ or ❎ session so the mark comes off), end your reply with the command for me to run, e.g.
`/rename ✅ DEV-1234 ➔ W#105 | Short title`.
EOF
  echo "$DELIM"
} > "$T"

size=$(wc -c < "$T" | tr -d ' ')
if cmp -s "$T" "$OUT"; then
  echo "OK: cloud setup script already current ($size bytes)"
else
  cp "$T" "$OUT" && chmod +x "$OUT"
  echo "OK: cloud setup script regenerated ($size bytes): $OUT"
fi
[ "$size" -gt 60000 ] && echo "WARN: cloud setup script is $size bytes; the documented CLAUDE.md file limit is 64 KB."
[ -e "$FLAG" ] && echo "NOTE: cloud setup includes the personal overlay (remove $FLAG to leave it out)." ||
  echo "NOTE: cloud setup leaves the personal overlay out (touch $FLAG to include it)."
exit 0
